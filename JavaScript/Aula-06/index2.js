//função anonima - sem nome. a função é armanezada em uma constante
const multiplicar = function (x, y) {
  return x * y;
};

// mostra o resultado no console da guia quando o elemento é inspecionado
console.log(multiplicar(10, 20));

// some a 'funcion', entra a '=>', função de sete, arrow funcion

const somar = (a, b) => {
  return a + b;
};
console.log(somar(10,20));